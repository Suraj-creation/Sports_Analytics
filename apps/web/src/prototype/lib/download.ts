import type { Match } from "../data/types";
import { STROKE_LABEL } from "../data/types";

/**
 * Real file exports.
 *
 * The engine already produces a PDF report, a rallies CSV, an events JSONL and a summary
 * JSON. The two that can be generated honestly in a browser from data the prototype holds
 * are built here for real — a download that actually lands is worth more than a button
 * that pretends. The PDF is the one that genuinely needs the server, and it says so.
 */

function save(name: string, mime: string, body: string) {
  const blob = new Blob([body], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  // Give the browser a tick to start the download before the handle goes.
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

function csvCell(v: unknown): string {
  const s = String(v ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** One row per rally, the shape the engine's rallies.csv uses. */
export function exportRalliesCsv(match: Match) {
  const head = [
    "rally_no",
    "game",
    "start_frame",
    "end_frame",
    "start_time",
    "duration_s",
    "shots",
    "server",
    "winner_side",
    "outcome",
    "end_reason",
    "counted",
    "score_a",
    "score_b",
  ];
  const rows = match.rallies.map((r) => [
    r.no,
    r.game,
    r.frames[0],
    r.frames[1],
    (r.frames[0] / match.fps).toFixed(2),
    r.durationS,
    r.shots.length,
    r.server,
    r.winner ?? "",
    r.outcome,
    r.endReason,
    r.official ? "yes" : "no",
    r.scoreAfter.A,
    r.scoreAfter.B,
  ]);
  save(
    `${match.id}-rallies.csv`,
    "text/csv;charset=utf-8",
    [head, ...rows].map((r) => r.map(csvCell).join(",")).join("\n"),
  );
}

/** One JSON object per shot, newline delimited — the events JSONL shape. */
export function exportEventsJsonl(match: Match) {
  const lines: string[] = [];
  for (const r of match.rallies) {
    lines.push(
      JSON.stringify({
        type: "rally_end",
        rally_no: r.no,
        frame_start: r.frames[0],
        frame_end: r.frames[1],
        payload: {
          n_shots: r.shots.length,
          winner: r.winner,
          outcome: r.outcome,
          official: r.official,
          end_reason: r.endReason,
        },
      }),
    );
    for (const s of r.shots) {
      lines.push(
        JSON.stringify({
          type: "stroke",
          event_id: s.id,
          rally_no: r.no,
          frame: s.frame,
          actor: s.player,
          payload: { stroke: s.stroke, subtype: s.subtype ?? null, from: s.from, met_at: s.metAt },
        }),
      );
    }
  }
  save(`${match.id}-events.jsonl`, "application/x-ndjson", lines.join("\n"));
}

/** The aggregate summary, with the per-player stats as the engine reports them. */
export function exportSummaryJson(match: Match) {
  const body = {
    match: {
      id: match.id,
      title: match.title,
      date: match.date,
      venue: match.venue,
      court: match.court,
      discipline: match.discipline,
      games: match.games,
      duration_min: match.durationMin,
      active_play_s: match.activePlayS,
    },
    coverage: match.coverage,
    players: match.players.map((p) => ({
      id: p.id,
      name: p.name,
      side: p.side,
      stats: match.stats[p.id],
    })),
    pairs: match.pairs ?? null,
    note: "Generated by the Rally design prototype from fixture data. Not a measurement.",
  };
  save(`${match.id}-summary.json`, "application/json", JSON.stringify(body, null, 2));
}

/** Everything this device holds about you, for Settings → download. */
export function exportMyData(payload: Record<string, unknown>) {
  save(
    "rally-my-data.json",
    "application/json",
    JSON.stringify({ exported_at: new Date().toISOString(), ...payload }, null, 2),
  );
}

export function shotLabel(stroke: string) {
  return STROKE_LABEL[stroke] ?? stroke;
}
