import { copyFile, lstat, mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const mimeTypes = {
  '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8',
  '.avif': 'image/avif', '.gif': 'image/gif', '.ico': 'image/x-icon',
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png',
  '.svg': 'image/svg+xml', '.webp': 'image/webp',
  '.woff': 'font/woff', '.woff2': 'font/woff2', '.ttf': 'font/ttf', '.otf': 'font/otf',
  '.mp4': 'video/mp4', '.webm': 'video/webm', '.vtt': 'text/vtt; charset=utf-8',
  '.mp3': 'audio/mpeg', '.ogg': 'audio/ogg', '.wav': 'audio/wav',
  '.txt': 'text/plain; charset=utf-8',
};
const sourceExtensions = new Set(['.js', '.mjs', '.css']);
const marker = '.rally-static-output';
const ownership = 'Generated by Rally static build.\n';

export function isMain(url) {
  return Boolean(process.argv[1]) && url === pathToFileURL(path.resolve(process.argv[1])).href;
}

export function parseArgs(args, defaults, allowed = Object.keys(defaults)) {
  const result = { ...defaults };
  for (let i = 0; i < args.length; i += 2) {
    const key = args[i].slice(2);
    if (!args[i].startsWith('--') || !allowed.includes(key) || !args[i + 1] || args[i + 1].startsWith('--')) {
      throw new Error(`Unknown or incomplete option: ${args[i]}`);
    }
    result[key] = args[i + 1];
  }
  return result;
}

export async function publicFiles(directory) {
  const root = path.resolve(directory);
  const rootInfo = await lstat(root);
  if (rootInfo.isSymbolicLink() || !rootInfo.isDirectory()) throw new Error('Public root must be a directory, never a symlink.');
  const files = [];
  async function visit(relative) {
    const absolute = path.join(root, relative);
    const info = await lstat(absolute);
    if (info.isSymbolicLink()) throw new Error(`Symlink is not public: ${relative}`);
    const parts = relative.split('/');
    if (parts.some((part) => part.startsWith('.') || part === 'node_modules')) throw new Error(`Hidden or private path is not public: ${relative}`);
    if (info.isDirectory()) {
      if (relative === 'index.html') throw new Error('index.html must be a regular file.');
      for (const name of (await readdir(absolute)).sort()) await visit(`${relative}/${name}`);
      return;
    }
    const extension = path.extname(relative).toLowerCase();
    const allowed = relative === 'index.html' || relative === 'assets/fonts/LICENSE.txt' || (parts[0] === 'src' ? sourceExtensions.has(extension) : Boolean(mimeTypes[extension]) && !sourceExtensions.has(extension) && !['.html', '.txt'].includes(extension));
    if (!info.isFile() || !allowed) throw new Error(`Unsupported file is not public: ${relative}`);
    files.push(relative);
  }
  await visit('index.html');
  for (const name of ['src', 'assets']) {
    try { await lstat(path.join(root, name)); } catch (error) {
      if (error.code === 'ENOENT') continue;
      throw error;
    }
    await visit(name);
  }
  return files;
}

async function ownedOutput(directory) {
  let info;
  try { info = await lstat(directory); } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
  if (info.isSymbolicLink()) throw new Error('Output dist must never be a symlink.');
  if (!info.isDirectory()) throw new Error('Refusing to replace an unowned dist.');
  try {
    const markerPath = path.join(directory, marker);
    const markerInfo = await lstat(markerPath);
    if (markerInfo.isFile() && !markerInfo.isSymbolicLink() && await readFile(markerPath, 'utf8') === ownership) return true;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  throw new Error('Refusing to replace an unowned dist. Move or rename it first.');
}

export async function build(directory = packageRoot) {
  const root = path.resolve(directory);
  const files = await publicFiles(root);
  const output = path.join(root, 'dist');
  const exists = await ownedOutput(output);
  const staging = await mkdtemp(path.join(root, '.dist-build-'));
  try {
    for (const relative of files) {
      const destination = path.join(staging, relative);
      await mkdir(path.dirname(destination), { recursive: true });
      await copyFile(path.join(root, relative), destination);
    }
    await writeFile(path.join(staging, marker), ownership);
    if (exists) await rm(output, { recursive: true });
    await rename(staging, output);
  } finally {
    if (path.dirname(staging) === root && path.basename(staging).startsWith('.dist-build-')) await rm(staging, { recursive: true, force: true });
  }
  return { output, count: files.length };
}

if (isMain(import.meta.url)) {
  try {
    const options = parseArgs(process.argv.slice(2), { dir: packageRoot });
    const result = await build(options.dir);
    console.log(`Built ${result.count} public files in ${result.output}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
